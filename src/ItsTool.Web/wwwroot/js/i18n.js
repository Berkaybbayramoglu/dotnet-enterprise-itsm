/**
 * Gets the currently selected language from localStorage, defaults to 'tr'.
 */
export function getCurrentLanguage() {
    return localStorage.getItem('itsm_lang') || 'tr';
}

/**
 * Sets the new language and applies translations immediately.
 */
export function setLanguage(langCode) {
    if (translations[langCode]) {
        localStorage.setItem('itsm_lang', langCode);
        window.location.reload();
    }
}

/**
 * Helper function for dynamic JS translations
 */
export function t(key) {
    const lang = getCurrentLanguage();
    return translations[lang]?.[key] || key;
}

/**
 * Scans the DOM for [data-i18n] attributes and updates their text content.
 */
function applyTranslationToElement(el, dict) {
    const key = el.dataset.i18n;
    if (!dict[key]) return;

    const target = el.dataset.i18nTarget;
    if (target === 'placeholder') {
        el.placeholder = dict[key];
        return;
    }

    let textNodeFound = false;
    for (const node of el.childNodes) {
        if (node.nodeType === Node.TEXT_NODE && node.nodeValue.trim() !== '') {
            node.nodeValue = dict[key];
            textNodeFound = true;
            break;
        }
    }
    
    if (!textNodeFound) {
        if (el.childNodes.length === 0) {
            el.textContent = dict[key];
        } else {
            el.appendChild(document.createTextNode(' ' + dict[key]));
        }
    }
}

export function applyTranslations() {
    const lang = getCurrentLanguage();
    const dict = translations[lang];
    if (!dict) return;

    const elements = document.querySelectorAll('[data-i18n]');
    elements.forEach(el => applyTranslationToElement(el, dict));

    document.documentElement.lang = lang;
}

